// Converts a 10px BDF pixel font into the compact glyph table used to draw Chinese text on the panel.
// Usage: node scripts/build-pixel-font.mjs <font.bdf> [out.ts]
// Source font: Fusion Pixel Font 10px monospaced zh_hans (https://github.com/TakWolf/fusion-pixel-font, SIL OFL 1.1).
//
// Kept glyphs: printable ASCII, GB2312 (all simplified hanzi), Big5 level-1 (common traditional hanzi),
// CJK punctuation and full-width forms. Each glyph is rasterised into a cell of its advance width x 10 rows
// (ascent 9 + descent 1) and bit-packed; code points are delta-encoded varints.
import fs from "node:fs";
import path from "node:path";

const [, , bdfPath, outPath = "src/lib/agent-display/cjk-font-data.ts"] = process.argv;
if (!bdfPath) throw new Error("usage: node scripts/build-pixel-font.mjs <font.bdf> [out.ts]");

const HEIGHT = 10;
const ASCENT = 9;

function decodeTable(encoding, firstLead, lastLead, firstTrail, lastTrail) {
  const decoder = new TextDecoder(encoding, { fatal: true });
  const chars = new Set();
  for (let lead = firstLead; lead <= lastLead; lead++) {
    for (let trail = firstTrail; trail <= lastTrail; trail++) {
      try {
        const ch = decoder.decode(Uint8Array.of(lead, trail));
        if ([...ch].length === 1) chars.add(ch.codePointAt(0));
      } catch {
        // unassigned code point in this table
      }
    }
  }
  return chars;
}

function wantedCodePoints() {
  const wanted = new Set();
  for (let cp = 0x20; cp <= 0x7e; cp++) wanted.add(cp);
  for (let cp = 0x3000; cp <= 0x303f; cp++) wanted.add(cp); // CJK symbols and punctuation
  for (let cp = 0xff01; cp <= 0xff5e; cp++) wanted.add(cp); // full-width forms
  for (const cp of [0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0x2014, 0x00b7, 0x2022, 0x00d7]) wanted.add(cp);
  decodeTable("gbk", 0xa1, 0xf7, 0xa1, 0xfe).forEach(cp => wanted.add(cp)); // GB2312 region of GBK
  decodeTable("big5", 0xa4, 0xc6, 0x40, 0xfe).forEach(cp => wanted.add(cp)); // Big5 common characters
  return wanted;
}

function parseBdf(text) {
  const glyphs = new Map();
  const blocks = text.split("STARTCHAR").slice(1);
  for (const block of blocks) {
    const encoding = Number(/\nENCODING (-?\d+)/.exec(block)?.[1]);
    const dwidth = Number(/\nDWIDTH (\d+)/.exec(block)?.[1]);
    const bbx = /\nBBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)/.exec(block)?.slice(1).map(Number);
    const bitmap = /\nBITMAP\n([\s\S]*?)\nENDCHAR/.exec(block)?.[1].trim().split("\n").filter(Boolean) ?? [];
    if (!Number.isFinite(encoding) || encoding < 0 || !bbx) continue;
    glyphs.set(encoding, { dwidth, bbx, bitmap });
  }
  return glyphs;
}

function rasterise({ dwidth, bbx: [w, h, xoff, yoff], bitmap }) {
  const bits = new Uint8Array(dwidth * HEIGHT);
  bitmap.forEach((hex, row) => {
    const value = BigInt(`0x${hex}`);
    const rowBits = hex.length * 4;
    for (let col = 0; col < w; col++) {
      if (!((value >> BigInt(rowBits - 1 - col)) & 1n)) continue;
      const x = xoff + col;
      const y = ASCENT - (yoff + h) + row; // top row of the bbox sits at baseline - (yoff + h)
      if (x >= 0 && x < dwidth && y >= 0 && y < HEIGHT) bits[y * dwidth + x] = 1;
    }
  });
  return bits;
}

function varint(value, out) {
  let v = value;
  while (v >= 0x80) {
    out.push((v & 0x7f) | 0x80);
    v >>>= 7;
  }
  out.push(v);
}

const glyphs = parseBdf(fs.readFileSync(bdfPath, "latin1"));
const codePoints = [...wantedCodePoints()].filter(cp => glyphs.has(cp)).sort((a, b) => a - b);
const index = [];
const data = [];
let previous = 0;
for (const cp of codePoints) {
  const glyph = glyphs.get(cp);
  varint(cp - previous, index);
  previous = cp;
  const bits = rasterise(glyph);
  data.push(glyph.dwidth);
  for (let i = 0; i < bits.length; i += 8) {
    let byte = 0;
    for (let b = 0; b < 8; b++) if (bits[i + b]) byte |= 0x80 >> b;
    data.push(byte);
  }
}

const header = `// Generated by scripts/build-pixel-font.mjs — do not edit.
// Glyphs from Fusion Pixel Font 10px (c) 2022 TakWolf, SIL Open Font License 1.1 (see ./FONT-LICENSE.txt).
// ${codePoints.length} glyphs: ASCII, GB2312, Big5 common, CJK punctuation, full-width forms.
`;
const body = `${header}
export const CJK_FONT_HEIGHT = ${HEIGHT};
export const CJK_FONT_GLYPH_COUNT = ${codePoints.length};
/** Delta-encoded varint code points, ascending. */
export const CJK_FONT_INDEX = "${Buffer.from(index).toString("base64")}";
/** Per glyph: advance width byte, then width x ${HEIGHT} bits row-major, MSB first, byte-padded. */
export const CJK_FONT_DATA = "${Buffer.from(data).toString("base64")}";
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, body);
console.log(`${codePoints.length} glyphs -> ${outPath} (${(body.length / 1024).toFixed(0)} KB)`);
