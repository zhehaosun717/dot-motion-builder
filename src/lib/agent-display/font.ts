export const GLYPH_WIDTH = 3;
export const GLYPH_HEIGHT = 5;
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1;

/** Glyph for a character; lowercase folds to uppercase and anything unknown becomes '?'. */
function glyphFor(ch: string) {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS["?"];
}

export function hasGlyph(ch: string) {
  return Boolean(GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()]);
}

export function measureText(text: string, scale = 1) {
  return text.length === 0 ? 0 : (text.length * GLYPH_ADVANCE - 1) * scale;
}

export function drawText(canvas: PixelCanvas, text: string, x: number, y: number, color: Rgb, scale = 1) {
  [...text].forEach((ch, i) => {
    glyphFor(ch).forEach((row, gy) => {
      [...row].forEach((bit, gx) => {
        if (bit === "#") canvas.fillRect(x + (i * GLYPH_ADVANCE + gx) * scale, y + gy * scale, scale, scale, color);
      });
    });
  });
}

/** Greedy word wrap to lines of at most maxChars; over-long words are split. */
export function wrapText(text: string, maxChars: number): string[] {
  const lines: string[] = [];
  let line = "";
  for (const word of text.trim().split(/\s+/).filter(Boolean)) {
    const pieces = word.match(new RegExp(`.{1,${maxChars}}`, "g")) ?? [];
    for (const piece of pieces) {
      if (!line) line = piece;
      else if (line.length + 1 + piece.length <= maxChars) line = `${line} ${piece}`;
      else {
        lines.push(line);
        line = piece;
      }
    }
  }
  if (line) lines.push(line);
  return lines;
}
